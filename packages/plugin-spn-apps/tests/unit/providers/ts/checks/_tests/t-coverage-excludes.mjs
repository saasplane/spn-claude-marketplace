// `coverage-excludes` — an exclude says why, and no percentage is ever enforced (RD.SUPPORT.APPS.133).
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { one, done, tree, PLUGIN } from "../../../../../helpers/harness.mjs";

const REPO = { "sprepo.json": '{"type":"APPS","config":{"mtype":"APPS","stack":"TS"}}\n' };
const JEST = (excludes = "") =>
  "module.exports = {\n  displayName: 'x',\n  coverageDirectory: 'cov',\n" +
  (excludes ? `  coveragePathIgnorePatterns: [\n${excludes}  ],\n` : "") +
  "};\n";
const VITEST = (excludes = "") =>
  "export default defineWebVitestConfig('x', {\n  test: {\n    coverage: {\n" +
  (excludes ? `      exclude: [\n${excludes}      ],\n` : "") +
  "      reporter: ['text', 'json-summary'],\n    },\n  },\n});\n";

console.log("=== coverage-excludes — known-bad");

one("[MKT.PROVIDERS.31] a new Jest exclude with no reason is refused", {
  script: "coverage-excludes", root: tree({ ...REPO, "jest.config.cjs": JEST("    '/src/a/',  // generated by the codegen\n") }),
  input: { file_path: "jest.config.cjs", old_string: "    '/src/a/',  // generated by the codegen\n",
           new_string: "    '/src/a/',  // generated by the codegen\n    '/src/hard/',\n" },
  expect: "deny", says: "`/src/hard/` carries no comment",
});

one("[MKT.PROVIDERS.31] a new Vitest exclude with no reason is refused", {
  script: "coverage-excludes", root: tree({ ...REPO, "vitest.config.ts": VITEST("        'src/a.ts',  // a vendor round trip\n") }),
  input: { file_path: "vitest.config.ts", old_string: "        'src/a.ts',  // a vendor round trip\n",
           new_string: "        'src/a.ts',  // a vendor round trip\n        'src/b.ts',\n" },
  expect: "deny", says: "`src/b.ts` carries no comment",
});

console.log("\n=== coverage-excludes — what it allows");

one("[MKT.PROVIDERS.31] a new exclude with its reason on the line above is allowed", {
  script: "coverage-excludes", root: tree({ ...REPO, "vitest.config.ts": VITEST("        'src/a.ts',  // a vendor round trip\n") }),
  input: { file_path: "vitest.config.ts", old_string: "        'src/a.ts',  // a vendor round trip\n",
           new_string: "        'src/a.ts',  // a vendor round trip\n        // a proof-of-person challenge, which no case can drive\n        'src/captcha.ts',\n" },
  expect: "",
});

one("an exclude already on disk without a reason is not this edit's to answer for", {
  script: "coverage-excludes", root: tree({ ...REPO, "jest.config.cjs": JEST("    '/src/old/',\n") }),
  input: { file_path: "jest.config.cjs", old_string: "coverageDirectory: 'cov'", new_string: "coverageDirectory: 'coverage'" },
  expect: "",
});

one("no percentage is read: a write that sets, lowers or removes a number is never refused", {
  script: "coverage-excludes", root: tree({ ...REPO, "jest.config.cjs": JEST() }),
  input: { file_path: "jest.config.cjs", content: "module.exports = {\n  displayName: 'x',\n  collectCoverage: true,\n};\n" },
  expect: "",
});

one("a Playwright configuration is never read", {
  script: "coverage-excludes", root: tree({ ...REPO }),
  input: { file_path: "playwright.config.ts", content: "export default {};\n" },
  expect: "",
});

// Through the one PreToolUse entry the plugin registers, so the rule is wired and not only written.
{
  const root = tree({ ...REPO, "packages/x/spkind.json": '{"kind":"SUPPORT_SERVER"}', "packages/x/jest.config.cjs": JEST("    '/src/a/',  // generated by the codegen\n") });
  const out = execFileSync("node", [resolve(PLUGIN, "src", "scripts", "events", "pretooluse.ts")], {
    input: JSON.stringify({ tool_name: "Edit", cwd: root, tool_input: {
      file_path: resolve(root, "packages/x/jest.config.cjs"),
      old_string: "    '/src/a/',  // generated by the codegen\n",
      new_string: "    '/src/a/',  // generated by the codegen\n    '/src/hard/',\n" } }),
    encoding: "utf8", cwd: root, env: { ...process.env, SPN_TELEMETRY: "off" },
  });
  const denied = out.includes('"permissionDecision":"deny"') && out.includes("`/src/hard/` carries no comment");
  console.log(`  ${denied ? "PASS" : "FAIL"}  [MKT.PROVIDERS.31] the plugin's one PreToolUse entry refuses the exclude with no reason`);
  // Outside the harness's own count, so a failure here stops the suite before its summary.
  if (!denied) { console.log(`        ${out.slice(0, 300)}`); process.exit(1); }
}

done("coverage-excludes");
